import streamlit as st
import numpy as np
import matplotlib.pyplot as plt

# ==========================================
# CONFIGURACIÓN DE LA PÁGINA
# ==========================================
st.set_page_config(page_title="Calculadora de Fatiga", layout="wide")
st.title("Calculadora de Fatiga en Ejes Escalonados")
st.markdown("Análisis interactivo de vida a la fatiga usando el método de Von Mises y diagramas de Smith/S-N.")

# ==========================================
# BARRA LATERAL: ENTRADA DE DATOS
# ==========================================
st.sidebar.header("Parámetros de Entrada")

st.sidebar.subheader("Geometría (mm)")
D = st.sidebar.slider("Diámetro Mayor (D)", min_value=20.0, max_value=100.0, value=50.0, step=1.0)
d = st.sidebar.slider("Diámetro Menor (d)", min_value=10.0, max_value=90.0, value=30.0, step=1.0)
r = st.sidebar.slider("Radio de Entalla (r)", min_value=0.1, max_value=10.0, value=3.0, step=0.1)

st.sidebar.subheader("Material (MPa)")
Sut = st.sidebar.slider("Esfuerzo Último (Sut)", min_value=300.0, max_value=800.0, value=460.0, step=10.0)
Sy = st.sidebar.slider("Esfuerzo de Fluencia (Sy)", min_value=150.0, max_value=600.0, value=250.0, step=10.0)

st.sidebar.subheader("Condiciones")
acabados = {
    "1. Rectificado": 1,
    "2. Maquinado/Laminado Frío": 2,
    "3. Laminado Caliente": 3,
    "4. Asforjado": 4
}
acabado_nombre = st.sidebar.selectbox("Acabado Superficial", options=list(acabados.keys()), index=1)
acabado_opc = acabados[acabado_nombre]
confiabilidad = st.sidebar.selectbox("Confiabilidad", options=[0.5, 0.9, 0.95, 0.99, 0.999], index=3)

st.sidebar.subheader("Cargas (N-m)")
Tmax = st.sidebar.slider("Torsión Máxima (Tmax)", min_value=-200.0, max_value=200.0, value=130.0, step=5.0)
Tmin = st.sidebar.slider("Torsión Mínima (Tmin)", min_value=-200.0, max_value=200.0, value=-80.0, step=5.0)
Mmax = st.sidebar.slider("Momento Máximo (Mmax)", min_value=0.0, max_value=200.0, value=130.0, step=5.0)
Mmin = st.sidebar.slider("Momento Mínimo (Mmin)", min_value=0.0, max_value=200.0, value=13.0, step=5.0)

# ==========================================
# LÓGICA DE CÁLCULO
# ==========================================
# 2. Análisis de Cargas
Ta = abs((Tmax - Tmin) / 2)
Tm = (Tmax + Tmin) / 2
Ma = abs((Mmax - Mmin) / 2)
Mm = (Mmax + Mmin) / 2

# 3. Factores de Marin
ka_params = {1: (1.58, -0.085), 2: (4.51, -0.265), 3: (57.7, -0.718), 4: (272, -0.995)}
a, b_ka = ka_params[acabado_opc]
ka = a * (Sut**b_ka)
kb = 1.24 * (d**-0.107) # Asumimos d en rango
ke_dict = {0.5: 1.0, 0.9: 0.897, 0.95: 0.868, 0.99: 0.814, 0.999: 0.753}
ke = ke_dict.get(confiabilidad, 0.814)

Se_prime = 0.5 * Sut
Se = ka * kb * ke * Se_prime

# 4. Concentración de Esfuerzos
Kt, Kts = 1.70, 1.45
sqrt_a_b = 1.24 - 2.25e-3*Sut + 1.60e-6*Sut**2 - 4.11e-10*Sut**3      # flexión [√mm]
sqrt_a_t = 0.958 - 1.83e-3*Sut + 1.43e-6*Sut**2 - 4.11e-10*Sut**3     # torsión [√mm]
q  = 1.0 if r <= 0.01 else 1 / (1 + sqrt_a_b/np.sqrt(r))
qs = 1.0 if r <= 0.01 else 1 / (1 + sqrt_a_t/np.sqrt(r))
Kf  = 1 + q  * (Kt  - 1)
Kfs = 1 + qs * (Kts - 1)

# 5. Esfuerzos Nominales
if d <= 0.01:
    st.error("El diámetro d debe ser mayor que cero.")
    st.stop()

def stress_flex(M): return (32 * M) / (np.pi * (d/1000)**3) / 1e6
def stress_tor(T): return (16 * T) / (np.pi * (d/1000)**3) / 1e6

sig_a = stress_flex(Ma)
sig_m = stress_flex(Mm)
tau_a = stress_tor(Ta)
tau_m = stress_tor(Tm)

# 6. Esfuerzos Von Mises
sig_prime_a = np.sqrt((Kf * sig_a)**2 + 3 * (Kfs * tau_a)**2)
sig_prime_m = np.sqrt((Kf * sig_m)**2 + 3 * (Kfs * tau_m)**2)

# 7. Factores de Seguridad
ny_langer = Sy / (sig_prime_a + sig_prime_m) if (sig_prime_a + sig_prime_m) != 0 else np.inf
n_goodman = 1 / (sig_prime_a/Se + sig_prime_m/Sut) if (sig_prime_a/Se + sig_prime_m/Sut) != 0 else np.inf
n_soderberg = 1 / (sig_prime_a/Se + sig_prime_m/Sy) if (sig_prime_a/Se + sig_prime_m/Sy) != 0 else np.inf
asme_denom_sq = (sig_prime_a/Se)**2 + (sig_prime_m/Sy)**2
n_asme = np.sqrt(1 / asme_denom_sq) if asme_denom_sq > 0 else np.inf

if sig_prime_m == 0 or sig_prime_a == 0 or Sut == 0 or Se == 0:
    n_gerber = np.inf
else:
    term_b = (2 * sig_prime_m * Se) / (sig_prime_a * Sut)
    sqrt_arg = 1 + term_b**2
    n_gerber = (1/2) * (Sut/sig_prime_m)**2 * (sig_prime_a/Se) * (-1 + np.sqrt(sqrt_arg)) if sqrt_arg >= 0 else np.inf

# ==========================================
# INTERFAZ DE RESULTADOS (MÉTRICAS)
# ==========================================
col1, col2, col3, col4 = st.columns(4)
col1.metric("Límite de Fatiga (Se)", f"{Se:.1f} MPa")
col2.metric("Von Mises Alternante", f"{sig_prime_a:.1f} MPa")
col3.metric("Von Mises Medio", f"{sig_prime_m:.1f} MPa")
col4.metric("Factor Langer (Fluencia)", f"{ny_langer:.2f}")

st.markdown("---")
st.markdown("### Factores de Seguridad a Vida Infinita")
c1, c2, c3, c4 = st.columns(4)
c1.metric("Goodman", f"{n_goodman:.2f}")
c2.metric("Soderberg", f"{n_soderberg:.2f}")
c3.metric("ASME Elíptica", f"{n_asme:.2f}")
c4.metric("Gerber", f"{n_gerber:.2f}")

# ==========================================
# FUNCIONES DE GRAFICACIÓN Y GRÁFICOS
# ==========================================
st.markdown("---")
st.markdown("### Diagramas de Falla")

fig, axes = plt.subplots(1, 2, figsize=(16, 6))

# --- GRÁFICA 1: SMITH ---
ax_smith = axes[0]
ax_smith.set_title('Diagrama de Smith (Sm vs Sa)')
ax_smith.set_xlabel('Esfuerzo Medio Equivalente (Sm) [MPa]')
ax_smith.set_ylabel('Esfuerzo Alternante Equivalente (Sa) [MPa]')
ax_smith.grid(True, linestyle='--', alpha=0.7)

max_x_val = max(Sut, Sy, sig_prime_m * 1.5, 10)
Sm_vals = np.linspace(0, max_x_val, 200)

Sa_goodman = Se * (1 - Sm_vals / Sut)
ax_smith.plot(Sm_vals, Sa_goodman, label='Goodman', color='blue')

Sa_soderberg = Se * (1 - Sm_vals / Sy)
ax_smith.plot(Sm_vals, Sa_soderberg, label='Soderberg', color='green', linestyle='--')

Sa_gerber = Se * (1 - (Sm_vals / Sut)**2)
ax_smith.plot(Sm_vals, Sa_gerber, label='Gerber', color='red', linestyle='-.')

Sa_asme = np.zeros_like(Sm_vals)
for i, Sm_val in enumerate(Sm_vals):
    arg = 1 - (Sm_val / Sy)**2
    if arg >= 0: Sa_asme[i] = Se * np.sqrt(arg)
ax_smith.plot(Sm_vals, Sa_asme, label='ASME', color='purple', linestyle=':')

Sa_langer = Sy - Sm_vals
Sa_langer[Sa_langer < 0] = np.nan
ax_smith.plot(Sm_vals, Sa_langer, label='Langer', color='brown', linestyle=':')

ax_smith.plot(sig_prime_m, sig_prime_a, 'o', color='orange', markersize=8, label='Punto de Operación')
ax_smith.annotate('', xy=(sig_prime_m, sig_prime_a), xytext=(0, 0), arrowprops=dict(facecolor='black', shrink=0.05, width=0.5, headwidth=5))

max_y_val = max(Se, sig_prime_a * 1.2) * 1.1
ax_smith.set_xlim(0, max_x_val * 1.1)
ax_smith.set_ylim(0, max_y_val)
ax_smith.legend()

# --- GRÁFICA 2: S-N ---
ax_sn = axes[1]
ax_sn.set_title('Diagrama S-N (Curva de Basquin)')
ax_sn.set_xlabel('Número de Ciclos (N)')
ax_sn.set_ylabel('Amplitud de Esfuerzo (Sa) [MPa]')
ax_sn.set_xscale('log')
ax_sn.set_yscale('log')
ax_sn.grid(True, which="both", ls="--", alpha=0.7)

N_low, S_low = 1000, 0.9 * Sut
N_high, S_high = 10**6, Se

if S_low > 0 and S_high > 0 and N_low < N_high and Sut > 0:
    b_sn = (np.log10(S_high) - np.log10(S_low)) / (np.log10(N_high) - np.log10(N_low))
    A_sn = 10**(np.log10(S_low) - b_sn * np.log10(N_low))

    N_cycles = np.logspace(1, 7, 500)
    Sn_curve = np.where(N_cycles < N_high, A_sn * (N_cycles**b_sn), Se)
    Sn_curve = np.minimum(Sn_curve, Sut)

    ax_sn.plot(N_cycles, Sn_curve, 'k-', label='Curva S-N')

    def calc_N(Sa_eq):
        if Sa_eq <= Se: return 10**7
        if Sa_eq > Sut: return 1
        return (Sa_eq / A_sn)**(1/b_sn)

    if (1 - sig_prime_m / Sut) > 0:
        Sa_eq_g = sig_prime_a / (1 - sig_prime_m / Sut)
        ax_sn.plot(calc_N(Sa_eq_g), Sa_eq_g, 'o', color='blue', label='Goodman Equivalente')
    if (1 - sig_prime_m / Sy) > 0:
        Sa_eq_s = sig_prime_a / (1 - sig_prime_m / Sy)
        ax_sn.plot(calc_N(Sa_eq_s), Sa_eq_s, 'o', color='green', label='Soderberg Equivalente')

    ax_sn.set_xlim(10, 10**7)
    ax_sn.set_ylim(Se * 0.8, max(Sut * 1.1, sig_prime_a * 1.5))
    ax_sn.legend()

st.pyplot(fig)
